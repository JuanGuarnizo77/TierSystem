class Command(BaseCommand):
    """Inserta los 49 cultivos faltantes en cultivos_cultivo para alcanzar 91 totales."""
    help = 'Inserta los 49 cultivos faltantes en el catálogo maestro (idempotente).'

    def handle(self, *args, **options):
        self.stdout.write(self.style.MIGRATE_HEADING('=== seed_cultivos_completo: iniciando ==='))
        creados = 0
        actualizados = 0

        for datos in NUEVOS_CULTIVOS:
            nombre = datos.pop('nombre')
            _, created = Cultivo.objects.update_or_create(
                nombre=nombre,
                defaults={
                    **datos,
                    'activo': True,
                }
            )
            # Restaurar nombre en datos para referencia (no altera la lista)
            datos['nombre'] = nombre
            if created:
                creados += 1
            else:
                actualizados += 1

        self.stdout.write(self.style.SUCCESS(
            f'\nCultivos creados: {creados} | Actualizados: {actualizados}'
        ))
        self.stdout.write(self.style.SUCCESS('=== seed_cultivos_completo: completado ==='))
